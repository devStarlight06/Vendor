// middleware/thumbnailService.js - CORRECTED VERSION
const axios = require('axios');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');
const Product = require('../models/Product');

// Master Prompt
const MASTER_PROMPT = `Create a premium product thumbnail for a Native91 marketplace listing. The product should be the hero of the image. 

Use a warm ivory or refined neutral background with elegant soft studio lighting. Add subtle realistic shadows for depth. Keep the composition clean with generous negative space.

The final image should look premium, editorial, sophisticated, minimal, and contemporary. Do not add any text, captions, slogans, prices, badges, labels, watermarks, or logos.

Focus on making the product look high-end and desirable.`;

class ThumbnailService {
  generateImageHash(imageUrl) {
    return crypto.createHash('sha256').update(imageUrl).digest('hex');
  }

  async checkExisting(productId, imageHash) {
    const product = await Product.findById(productId);
    if (!product) return null;

    if (product.thumbnail_status === 'COMPLETED' && 
        product.original_image_hash === imageHash) {
      return product.thumbnail_url;
    }
    return null;
  }

  async downloadImage(imageUrl) {
    try {
      if (imageUrl.startsWith('/uploads/')) {
        const filePath = path.join(__dirname, '..', imageUrl);
        if (fs.existsSync(filePath)) {
          return fs.readFileSync(filePath);
        }
        throw new Error(`Local file not found: ${imageUrl}`);
      }

      const response = await axios({
        method: 'GET',
        url: imageUrl,
        responseType: 'arraybuffer',
        timeout: 30000,
        maxRedirects: 5
      });
      return Buffer.from(response.data);
    } catch (error) {
      console.error('❌ Error downloading image:', error);
      throw new Error(`Failed to download image: ${error.message}`);
    }
  }

  getFullImageUrl(imagePath, baseUrl = process.env.BASE_URL || 'http://localhost:5177') {
    if (!imagePath) return null;
    if (imagePath.startsWith('http://') || imagePath.startsWith('https://')) {
      return imagePath;
    }
    if (imagePath.startsWith('/uploads/')) {
      return `${baseUrl}${imagePath}`;
    }
    if (!imagePath.startsWith('/') && !imagePath.startsWith('http')) {
      return `${baseUrl}/uploads/${imagePath}`;
    }
    return `${baseUrl}${imagePath}`;
  }

  async generateThumbnail(productId, imageUrl) {
    let product = await Product.findById(productId);
    if (!product) {
      throw new Error('Product not found');
    }

    const imageHash = this.generateImageHash(imageUrl);
    const existing = await this.checkExisting(productId, imageHash);
    if (existing) {
      console.log('✅ Thumbnail already exists for this product');
      return existing;
    }

    try {
      product.thumbnail_status = 'PROCESSING';
      product.thumbnail_retry_count = 0;
      product.thumbnail_error = null;
      await product.save();

      // Download the original image
      console.log('📥 Downloading original image...');
      const imageBuffer = await this.downloadImage(imageUrl);

      // Convert image to base64 for OpenAI
      const base64Image = imageBuffer.toString('base64');
      const mimeType = 'image/png';

      console.log('🎨 Generating thumbnail with OpenAI...');

      // ✅ CORRECT: Use DALL-E 3 with the required parameters
      const response = await axios.post(
        'https://api.openai.com/v1/images/generations',
        {
          model: "dall-e-3",
          prompt: `${MASTER_PROMPT}\n\nCreate a premium product thumbnail for: ${product.name}. ${product.description || 'Premium quality product'}`,
          n: 1,
          size: "1024x1024",
          quality: "standard"
        },
        {
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${process.env.OPENAI_API_KEY}`
          },
          timeout: 60000
        }
      );

      if (!response.data || !response.data.data || response.data.data.length === 0) {
        throw new Error('No image generated by OpenAI');
      }

      const generatedImageUrl = response.data.data[0].url;
      console.log('✅ Thumbnail generated successfully');

      // Download and save the generated image
      const thumbnailBuffer = await this.downloadImage(generatedImageUrl);
      const thumbnailPath = await this.saveThumbnail(productId, thumbnailBuffer);

      // Update product
      product.thumbnail_url = thumbnailPath;
      product.thumbnail_status = 'COMPLETED';
      product.thumbnail_generated_at = new Date();
      product.original_image_hash = imageHash;
      product.thumbnail_error = null;
      await product.save();

      return thumbnailPath;

    } catch (error) {
      console.error('❌ Thumbnail generation failed:');
      
      // Detailed error logging
      if (error.response && error.response.data) {
        console.error('Status:', error.response.status);
        console.error('Error Details:', JSON.stringify(error.response.data, null, 2));
      } else {
        console.error('Error:', error.message);
      }
      
      product.thumbnail_status = 'FAILED';
      product.thumbnail_retry_count = (product.thumbnail_retry_count || 0) + 1;
      product.thumbnail_error = error.response?.data?.error?.message || error.message;
      await product.save();

      throw error;
    }
  }

  async saveThumbnail(productId, buffer) {
    const dir = path.join(__dirname, '../uploads/products', productId);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }

    const filename = `native91-thumbnail.jpg`;
    const filepath = path.join(dir, filename);
    fs.writeFileSync(filepath, buffer);

    return `/uploads/products/${productId}/${filename}`;
  }

  async retryFailedThumbnails() {
    const maxRetries = 3;
    
    const failedProducts = await Product.find({
      thumbnail_status: 'FAILED',
      thumbnail_retry_count: { $lt: maxRetries }
    });

    console.log(`🔄 Found ${failedProducts.length} products to retry`);

    const results = [];
    for (const product of failedProducts) {
      try {
        const firstImage = product.image && product.image.length > 0 
          ? product.image[0] 
          : null;
        
        if (firstImage) {
          const fullUrl = this.getFullImageUrl(firstImage);
          if (fullUrl) {
            console.log(`🔄 Retrying thumbnail for product: ${product._id}`);
            const result = await this.generateThumbnail(product._id, fullUrl);
            results.push({ productId: product._id, success: true, result });
          } else {
            console.warn(`⚠️ No valid image URL for product ${product._id}`);
          }
        }
      } catch (error) {
        console.error(`❌ Retry failed for product ${product._id}:`, error);
        results.push({ 
          productId: product._id, 
          success: false, 
          error: error.message 
        });
      }
    }

    return results;
  }

  async getThumbnailStatus(productId) {
    const product = await Product.findById(productId);
    if (!product) {
      throw new Error('Product not found');
    }

    return {
      thumbnail_url: product.thumbnail_url,
      thumbnail_status: product.thumbnail_status,
      thumbnail_generated_at: product.thumbnail_generated_at,
      thumbnail_retry_count: product.thumbnail_retry_count,
      thumbnail_error: product.thumbnail_error
    };
  }

  getDisplayUrl(product) {
    if (!product) return null;
    
    if (product.thumbnail_status === 'COMPLETED' && product.thumbnail_url) {
      const baseUrl = process.env.BASE_URL || 'http://localhost:5177';
      return product.thumbnail_url.startsWith('http') 
        ? product.thumbnail_url 
        : `${baseUrl}${product.thumbnail_url}`;
    }
    
    if (product.image && product.image.length > 0) {
      const baseUrl = process.env.BASE_URL || 'http://localhost:5177';
      const img = product.image[0];
      return img.startsWith('http') ? img : `${baseUrl}${img}`;
    }
    
    return null;
  }
}

module.exports = new ThumbnailService();